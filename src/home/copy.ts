export const T: Record<Lang, Record<CopyKey, string>> = { en, pt };

/** The text of `key` in `lang`. It falls back to English, then to the key itself (mock line 852). */
export function translate(lang: Lang, key: string): string {
	const k = key as CopyKey;
	return T[lang][k] ?? T.en[k] ?? key;
}
